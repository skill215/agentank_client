class FeatureRegistry {
  constructor() {
    this.count = FEATURE.COUNT;
    this.family = new Uint8Array(POLICY_CAPACITY.MAX_FEATURES);
    this.minimum = new Int16Array(POLICY_CAPACITY.MAX_FEATURES);
    this.maximum = new Int16Array(POLICY_CAPACITY.MAX_FEATURES);
    this.costTier = new Uint8Array(POLICY_CAPACITY.MAX_FEATURES);
    this.dependencyMask = new Uint16Array(POLICY_CAPACITY.MAX_FEATURES);
    this.inputIndex = new Uint8Array(POLICY_CAPACITY.MAX_FEATURES);
    this.handlerCode = new Uint8Array(POLICY_CAPACITY.MAX_FEATURES);
    this.ownership = new Uint8Array(POLICY_CAPACITY.MAX_FEATURES);
    this.version = new Uint8Array(POLICY_CAPACITY.MAX_FEATURES);
    for (let index = 0; index < DESCRIPTORS.length; index += 1) {
      const d = DESCRIPTORS[index]; this.family[index] = d[0]; this.minimum[index] = d[1];
      this.maximum[index] = d[2]; this.costTier[index] = d[3]; this.dependencyMask[index] = d[4];
      this.inputIndex[index] = d[5]; this.handlerCode[index] = d[6]; this.version[index] = 1;
    }
    this.ownership[FEATURE.DANGER_SLACK] = FEATURE_OWNERSHIP.RISK_OWNED;
    this.ownership[FEATURE.POSSIBLE_SHOT_EXPOSURE] = FEATURE_OWNERSHIP.RISK_OWNED;
    this.ownership[FEATURE.OPPONENT_ATTACK_FIT] = FEATURE_OWNERSHIP.RISK_OWNED;
    this.ownership[FEATURE.DIRECT_HIT_WINDOW] = FEATURE_OWNERSHIP.COMBAT_OWNED;
    this.ownership[FEATURE.ESCAPE_DENIAL] = FEATURE_OWNERSHIP.COMBAT_OWNED;
    this.hotAllocationCount = 0;
  }
  descriptorComplete(index) {
    return index >= 0 && index < this.count && this.maximum[index] >= this.minimum[index] &&
      this.dependencyMask[index] !== 0 && this.handlerCode[index] !== 0 && this.version[index] !== 0;
  }
}

module.exports = { DESCRIPTORS, FeatureRegistry };
